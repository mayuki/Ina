using System.Text;
using Ina.Linker.MachO;

namespace Ina.Linker.Abi;

/// <summary>A dynamic library of macOS as input for <see cref="MacOSAbiTableGenerator"/>.</summary>
/// <param name="Stub">The content of the text-based stub (<c>.tbd</c>) that the SDK ships in place of the library.</param>
/// <param name="Complete">
/// Whether all exported symbols are listed. Otherwise only the ones that the native libraries of the .NET runtime
/// refer to are, which keeps the table small for frameworks that export tens of thousands of symbols.
/// </param>
public sealed record MacOSLibraryStub(string Stub, bool Complete);

/// <summary>
/// Generates an import table (see <see cref="ImportLibrarySet.Parse"/>) for macOS from the text-based stubs of an
/// SDK. The table only records which library exports which symbol; no code is copied.
/// </summary>
public static class MacOSAbiTableGenerator
{
    /// <param name="libraries">The libraries in the order in which a symbol that several of them export is attributed.</param>
    /// <param name="neededOrder">Install names in the order in which the libraries are listed as dependencies.</param>
    /// <param name="runtimeFiles">
    /// Object files and archives of the NativeAOT runtime packs; their undefined symbols select what is listed for
    /// libraries that are not <see cref="MacOSLibraryStub.Complete"/>.
    /// </param>
    /// <returns>The referenced symbols that none of the libraries exports.</returns>
    public static IReadOnlyList<string> Generate(
        TextWriter output, TargetArchitecture architecture, Version minimumOS, Version sdk, IReadOnlyList<MacOSLibraryStub> libraries,
        IReadOnlyList<string> neededOrder, IEnumerable<LinkInput> runtimeFiles)
    {
        var architectureName = architecture == TargetArchitecture.Arm64 ? "arm64" : "x86_64";
        var referenced = ReferencedSymbols(architecture, runtimeFiles);
        var parsed = libraries.Select(library => (Library: TextBasedStub.Parse(library.Stub, architectureName, minimumOS), library.Complete)).ToList();

        output.Write("# Generated by eng/generate-macos-abi.sh. Do not edit by hand.\n");
        output.Write("# Which system library exports which symbol; used to link without the libraries or the SDK.\n");
        output.Write($"target macOS {minimumOS} {architectureName} (SDK {sdk})\n");
        output.Write("interp /usr/lib/dyld\n");
        output.Write($"platform macos {minimumOS} {sdk}\n");

        // A library is identified by its install name. Its versions come from its own stub when there is one.
        var versions = new Dictionary<string, (Version Compatibility, Version Current)>(StringComparer.Ordinal);
        foreach (var (library, _) in parsed)
        {
            versions.TryAdd(library.InstallName, (library.CompatibilityVersion, library.CurrentVersion));
        }

        var sections = new List<(string InstallName, List<string> Symbols, List<string> ThreadLocals)>();
        (string InstallName, List<string> Symbols, List<string> ThreadLocals) Section(string installName)
        {
            var index = sections.FindIndex(section => section.InstallName == installName);
            if (index < 0)
            {
                index = sections.Count;
                sections.Add((installName, [], []));
            }

            return sections[index];
        }

        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (library, complete) in parsed)
        {
            foreach (var (names, isThreadLocal) in new[] { (library.Symbols, false), (library.ThreadLocalSymbols, true) })
            {
                foreach (var name in names)
                {
                    if ((!complete && !referenced.Contains(name)) || !seen.Add(name))
                    {
                        continue;
                    }

                    // On the oldest supported system a symbol may live in another library than in the SDK.
                    var installName = library.InstallName;
                    if (library.PreviousLibraries.TryGetValue(name, out var previous) || (previous = library.PreviousLibrary).InstallName is not null)
                    {
                        installName = previous.InstallName;
                        versions.TryAdd(installName, (previous.Compatibility, previous.Compatibility));
                    }

                    var section = Section(installName);
                    (isThreadLocal ? section.ThreadLocals : section.Symbols).Add(name);
                }
            }
        }

        // Only libraries that contribute a symbol are dependencies an executable can have.
        var listed = sections.Select(static section => section.InstallName).ToList();
        output.Write($"needed {string.Join(' ', neededOrder.Where(listed.Contains).Concat(listed.Where(name => !neededOrder.Contains(name))))}\n");

        foreach (var (installName, symbols, threadLocals) in sections)
        {
            var (compatibility, current) = versions[installName];
            output.Write($"lib {installName}\n");
            output.Write($"libver {compatibility} {current}\n");
            symbols.Sort(StringComparer.Ordinal);
            threadLocals.Sort(StringComparer.Ordinal);
            WriteSymbols(output, "S", symbols);
            WriteSymbols(output, "T", threadLocals);
        }

        return referenced.Where(name => !seen.Contains(name)).Order(StringComparer.Ordinal).ToList();
    }

    /// <summary>The symbols that the given object files and archives need from outside.</summary>
    private static HashSet<string> ReferencedSymbols(TargetArchitecture architecture, IEnumerable<LinkInput> runtimeFiles)
    {
        var cpuType = MachTarget.Create(architecture).CpuType;
        var undefined = new HashSet<string>(StringComparer.Ordinal);
        var defined = new HashSet<string>(StringComparer.Ordinal);

        void Scan(string name, ReadOnlyMemory<byte> data)
        {
            if (!MachObjectFile.IsMachObject(data.Span))
            {
                return;
            }

            var file = MachObjectFile.Parse(name, data);
            if (file.CpuType != cpuType)
            {
                throw new LinkerException($"{name}: object file was built for a different architecture than the table");
            }

            foreach (var symbol in file.Nlist)
            {
                if (symbol.IsStab || !symbol.IsExternal)
                {
                    continue;
                }

                (symbol.IsUndefined ? undefined : defined).Add(symbol.Name);
            }
        }

        foreach (var input in runtimeFiles)
        {
            if (ArchiveFile.IsArchive(input.Data.Span))
            {
                foreach (var (member, data) in ArchiveFile.Parse(input.Name, input.Data, static (_, _) => null).Members())
                {
                    Scan($"{input.Name}({member})", data);
                }
            }
            else
            {
                Scan(input.Name, input.Data);
            }
        }

        undefined.ExceptWith(defined);
        return undefined;
    }

    private static void WriteSymbols(TextWriter output, string keyword, List<string> names)
    {
        // Wrap the lines so that diffs of regenerated tables stay readable.
        var line = new StringBuilder(keyword);
        foreach (var name in names)
        {
            if (line.Length > keyword.Length && line.Length + name.Length + 1 > 120)
            {
                output.Write(line.Append('\n'));
                line.Clear().Append(keyword);
            }

            line.Append(' ').Append(name);
        }

        if (line.Length > keyword.Length)
        {
            output.Write(line.Append('\n'));
        }
    }

    /// <summary>
    /// The parts of a text-based stub file (TBD version 4, a YAML dialect) that matter for linking. A file holds
    /// one document per library: the library itself and the private libraries it re-exports, whose symbols count as
    /// its own.
    /// </summary>
    private sealed class TextBasedStub
    {
        public string InstallName { get; private set; } = string.Empty;

        public Version CurrentVersion { get; private set; } = new(1, 0, 0);

        public Version CompatibilityVersion { get; private set; } = new(1, 0, 0);

        public List<string> Symbols { get; } = [];

        public List<string> ThreadLocalSymbols { get; } = [];

        /// <summary>
        /// Symbols that live in another library on the oldest supported system, with the install name and the
        /// compatibility version of that library. Apple moves code between libraries; an executable has to name the
        /// library that has the symbol on the oldest system, which newer systems keep as a forwarding stub.
        /// </summary>
        public Dictionary<string, (string InstallName, Version Compatibility)> PreviousLibraries { get; } = new(StringComparer.Ordinal);

        /// <summary>The library that all symbols lived in on the oldest supported system, when the whole library was split off later.</summary>
        public (string InstallName, Version Compatibility) PreviousLibrary { get; private set; }

        public static TextBasedStub Parse(string text, string architecture, Version minimumOS)
        {
            var stub = new TextBasedStub();
            var isFirstDocument = true;
            var topLevelKey = string.Empty;
            var applies = false;
            var lines = text.Split('\n');
            for (var i = 0; i < lines.Length; i++)
            {
                var line = lines[i].TrimEnd('\r');
                if (line.StartsWith("--- ", StringComparison.Ordinal))
                {
                    if (!line.Contains("!tapi-tbd", StringComparison.Ordinal))
                    {
                        throw new LinkerException("unsupported stub file: expected a text-based stub (TBD) document");
                    }

                    isFirstDocument = stub.InstallName.Length == 0;
                    topLevelKey = string.Empty;
                    continue;
                }

                if (line.Length == 0 || line == "...")
                {
                    continue;
                }

                var (key, value) = SplitKey(line);
                if (key is null)
                {
                    continue;
                }

                if (!char.IsWhiteSpace(line[0]))
                {
                    topLevelKey = key;
                    switch (key)
                    {
                        case "tbd-version" when value.Trim() != "4":
                            throw new LinkerException($"unsupported stub file: TBD version {value.Trim()} (expected 4)");
                        case "install-name" when isFirstDocument:
                            stub.InstallName = Unquote(value.Trim());
                            break;
                        case "current-version" when isFirstDocument:
                            stub.CurrentVersion = ParseVersion(value);
                            break;
                        case "compatibility-version" when isFirstDocument:
                            stub.CompatibilityVersion = ParseVersion(value);
                            break;
                    }

                    continue;
                }

                // Inside "exports" and "reexports", every list item starts with the targets it applies to.
                if (topLevelKey is not ("exports" or "reexports"))
                {
                    continue;
                }

                if (key is not ("targets" or "symbols" or "weak-symbols" or "thread-local-symbols" or "objc-classes" or "objc-eh-types" or "objc-ivars"))
                {
                    continue;
                }

                var items = ReadSequence(lines, ref i, value);
                if (key == "targets")
                {
                    // The stubs of system libraries only name arm64e; its symbols are the ones arm64 code binds to.
                    applies = items.Exists(target => target == $"{architecture}-macos" || (architecture == "arm64" && target == "arm64e-macos"));
                    continue;
                }

                if (!applies)
                {
                    continue;
                }

                foreach (var item in items)
                {
                    // "$ld$..." entries are instructions for the linker about older OS versions, not symbols. The
                    // others (hide, add, weak, install_name) only concern systems older than any Ina targets.
                    if (item.StartsWith("$ld$", StringComparison.Ordinal))
                    {
                        stub.ReadPreviousLibrary(item, minimumOS);
                        continue;
                    }

                    switch (key)
                    {
                        case "symbols" or "weak-symbols":
                            stub.Symbols.Add(item);
                            break;
                        case "thread-local-symbols":
                            stub.ThreadLocalSymbols.Add(item);
                            break;
                        case "objc-classes":
                            stub.Symbols.Add("_OBJC_CLASS_$_" + item);
                            stub.Symbols.Add("_OBJC_METACLASS_$_" + item);
                            break;
                        case "objc-eh-types":
                            stub.Symbols.Add("_OBJC_EHTYPE_$_" + item);
                            break;
                        case "objc-ivars":
                            stub.Symbols.Add("_OBJC_IVAR_$_" + item);
                            break;
                    }
                }
            }

            if (stub.InstallName.Length == 0)
            {
                throw new LinkerException("malformed stub file: no install-name");
            }

            return stub;
        }

        /// <summary>
        /// Interprets <c>$ld$previous$install name$compatibility version$platform$first version$end version$symbol$</c>:
        /// for deployment targets in the given range, the symbol belongs to the library with that install name.
        /// </summary>
        private void ReadPreviousLibrary(string directive, Version minimumOS)
        {
            const string prefix = "$ld$previous$";
            const string macOS = "1";
            if (!directive.StartsWith(prefix, StringComparison.Ordinal) || !directive.EndsWith('$'))
            {
                return;
            }

            // The symbol comes last because it may contain the separator itself. Without a symbol the directive
            // is about everything the library exports.
            var fields = directive[prefix.Length..^1].Split('$', 6);
            if (fields.Length != 6 || fields[2] != macOS)
            {
                return;
            }

            var first = ParseVersion(fields[3]);
            var end = ParseVersion(fields[4]);
            var target = new Version(minimumOS.Major, minimumOS.Minor, Math.Max(minimumOS.Build, 0));
            if (target < first || target >= end)
            {
                return;
            }

            var previous = (fields[0], ParseVersion(fields[1].Length > 0 ? fields[1] : "1"));
            if (fields[5].Length > 0)
            {
                PreviousLibraries[fields[5]] = previous;
            }
            else
            {
                PreviousLibrary = previous;
            }
        }

        /// <summary>Splits "  - key: value" into key and value; returns a null key for lines without one.</summary>
        private static (string? Key, string Value) SplitKey(string line)
        {
            var content = line.TrimStart(' ', '-');
            var colon = content.IndexOf(':');
            if (colon <= 0 || content[0] is '[' or '\'' or '"')
            {
                return (null, string.Empty);
            }

            return (content[..colon], content[(colon + 1)..]);
        }

        /// <summary>Reads a flow sequence ("[ a, 'b', c ]"), which may continue on the following lines.</summary>
        private static List<string> ReadSequence(string[] lines, ref int index, string firstLine)
        {
            var items = new List<string>();
            var text = firstLine;
            var item = new StringBuilder();
            var quote = '\0';
            var started = false;
            while (true)
            {
                for (var c = 0; c < text.Length; c++)
                {
                    var character = text[c];
                    if (quote != '\0')
                    {
                        if (character != quote)
                        {
                            item.Append(character);
                        }
                        else if (quote == '\'' && c + 1 < text.Length && text[c + 1] == '\'')
                        {
                            // A doubled quote is an escaped quote.
                            item.Append('\'');
                            c++;
                        }
                        else
                        {
                            quote = '\0';
                        }

                        continue;
                    }

                    switch (character)
                    {
                        case '[':
                            started = true;
                            break;
                        case '\'' or '"' when started:
                            quote = character;
                            break;
                        case ',' or ']' when started:
                            if (item.Length > 0)
                            {
                                items.Add(item.ToString());
                                item.Clear();
                            }

                            if (character == ']')
                            {
                                return items;
                            }

                            break;
                        default:
                            if (started && !char.IsWhiteSpace(character))
                            {
                                item.Append(character);
                            }

                            break;
                    }
                }

                if (!started || index + 1 >= lines.Length)
                {
                    return items;
                }

                text = lines[++index].TrimEnd('\r');
            }
        }

        private static string Unquote(string value) => value.Length >= 2 && value[0] is '\'' or '"' && value[^1] == value[0] ? value[1..^1] : value;

        private static Version ParseVersion(string value)
        {
            var parts = Unquote(value.Trim()).Split('.');
            int Part(int index) => index < parts.Length && int.TryParse(parts[index], out var number) ? number : 0;
            return new Version(Part(0), Part(1), Part(2));
        }
    }
}
