using Ina.Linker.Elf;

namespace Ina.Linker.Abi;

/// <summary>
/// Generates an import table (see <see cref="ImportLibrarySet.Parse"/>) from the shared libraries of a target
/// system. The table only records exported symbol names with their default versions; no code is copied.
/// </summary>
public static class AbiTableGenerator
{
    private const int SectionHeaderSize = 64;
    private const int SymbolSize = 24;
    private const ushort VersionHidden = 0x8000;

    /// <param name="libraries">
    /// The libraries, by SONAME, in the order in which a name that several of them export is attributed.
    /// </param>
    /// <param name="neededOrder">The order in which the libraries are listed as dependencies.</param>
    public static void Generate(
        TextWriter output, string description, string interpreter, IReadOnlyList<(string SoName, ReadOnlyMemory<byte> Data)> libraries,
        IReadOnlyList<string> neededOrder)
    {
        output.Write("# Generated by eng/generate-abi.sh. Do not edit by hand.\n");
        output.Write("# Exported symbols and their default versions; used to link without the libraries themselves.\n");
        output.Write($"target {description}\n");
        output.Write($"interp {interpreter}\n");
        output.Write($"needed {string.Join(' ', neededOrder)}\n");

        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (soName, data) in libraries)
        {
            var symbols = ReadExports(soName, data.Span).Where(s => seen.Add(s.Name)).ToList();
            output.Write($"lib {soName}\n");
            foreach (var byVersion in symbols.GroupBy(static s => s.Version).OrderBy(static g => VersionKey(g.Key)))
            {
                output.Write($"ver {byVersion.Key ?? "-"}\n");
                foreach (var byKind in byVersion.GroupBy(static s => s.Kind).OrderBy(static g => g.Key))
                {
                    var keyword = byKind.Key switch
                    {
                        ImportedSymbolKind.Function => "F",
                        ImportedSymbolKind.Object => "D",
                        _ => "T",
                    };

                    // Wrap the lines so that diffs of regenerated tables stay readable.
                    var line = keyword;
                    foreach (var name in byKind.Select(static s => s.Name).Order(StringComparer.Ordinal))
                    {
                        if (line.Length + name.Length + 1 > 120)
                        {
                            output.Write(line + "\n");
                            line = keyword;
                        }

                        line += " " + name;
                    }

                    output.Write(line + "\n");
                }
            }
        }
    }

    /// <summary>Sorts versions numerically (GLIBC_2.3 before GLIBC_2.10) with unversioned symbols first.</summary>
    private static (int, int, int, string) VersionKey(string? version)
    {
        if (version is null)
        {
            return (-1, 0, 0, string.Empty);
        }

        var numbers = version[(version.LastIndexOf('_') + 1)..].Split('.');
        int Part(int index) => index < numbers.Length && int.TryParse(numbers[index], out var value) ? value : 0;
        return (Part(0), Part(1), Part(2), version);
    }

    private static List<(string Name, string? Version, ImportedSymbolKind Kind)> ReadExports(string soName, ReadOnlySpan<byte> data)
    {
        if (!Input.ObjectFile.IsElf(data) || data[4] != 2 || data[5] != 1 || LittleEndian.U16(data, 0x10) != ElfType.Dyn)
        {
            throw new LinkerException($"{soName}: not a 64-bit little-endian ELF shared object");
        }

        var sectionOffset = (int)LittleEndian.U64(data, 0x28);
        var sectionCount = LittleEndian.U16(data, 0x3c);
        static ReadOnlySpan<byte> Header(ReadOnlySpan<byte> data, int sectionOffset, int index) =>
            data.Slice(sectionOffset + index * SectionHeaderSize, SectionHeaderSize);
        static ReadOnlySpan<byte> Content(ReadOnlySpan<byte> data, ReadOnlySpan<byte> header) =>
            data.Slice((int)LittleEndian.U64(header, 24), (int)LittleEndian.U64(header, 32));

        ReadOnlySpan<byte> symbols = default, strings = default, versionSymbols = default, versionDefinitions = default;
        for (var i = 0; i < sectionCount; i++)
        {
            var header = Header(data, sectionOffset, i);
            switch (LittleEndian.U32(header, 4))
            {
                case SectionType.DynSym:
                    symbols = Content(data, header);
                    strings = Content(data, Header(data, sectionOffset, (int)LittleEndian.U32(header, 40)));
                    break;
                case SectionType.GnuVerSym:
                    versionSymbols = Content(data, header);
                    break;
                case SectionType.GnuVerDef:
                    versionDefinitions = Content(data, header);
                    break;
            }
        }

        // Version definitions form a linked list; each one has a list of names of which the first is its own.
        var versionNames = new Dictionary<int, string>();
        for (var offset = 0; offset + 20 <= versionDefinitions.Length;)
        {
            var index = LittleEndian.U16(versionDefinitions, offset + 4) & 0x7fff;
            var aux = offset + (int)LittleEndian.U32(versionDefinitions, offset + 12);
            versionNames[index] = LittleEndian.CString(strings, (int)LittleEndian.U32(versionDefinitions, aux));
            var next = (int)LittleEndian.U32(versionDefinitions, offset + 16);
            if (next == 0)
            {
                break;
            }

            offset += next;
        }

        var exports = new List<(string, string?, ImportedSymbolKind)>();
        for (var i = 1; i < symbols.Length / SymbolSize; i++)
        {
            var symbol = symbols.Slice(i * SymbolSize, SymbolSize);
            var binding = symbol[4] >> 4;
            var type = symbol[4] & 0xf;
            if (LittleEndian.U16(symbol, 6) == SectionIndex.Undefined || binding == SymbolBinding.Local)
            {
                continue;
            }

            ImportedSymbolKind kind;
            switch (type)
            {
                case SymbolType.Func or SymbolType.GnuIFunc or SymbolType.NoType:
                    kind = ImportedSymbolKind.Function;
                    break;
                case SymbolType.Object:
                    kind = ImportedSymbolKind.Object;
                    break;
                case SymbolType.Tls:
                    kind = ImportedSymbolKind.Tls;
                    break;
                default:
                    continue;
            }

            string? version = null;
            if (versionSymbols.Length >= (i + 1) * 2)
            {
                var versionIndex = LittleEndian.U16(versionSymbols, i * 2);
                if ((versionIndex & VersionHidden) != 0 || versionIndex == 0)
                {
                    // Hidden versions exist only for old binaries; a linker never binds new references to them.
                    continue;
                }

                if (versionIndex > 1 && versionNames.TryGetValue(versionIndex, out var name))
                {
                    if (name.EndsWith("_PRIVATE", StringComparison.Ordinal))
                    {
                        continue;
                    }

                    version = name;
                }
            }

            exports.Add((LittleEndian.CString(strings, (int)LittleEndian.U32(symbol, 0)), version, kind));
        }

        return exports;
    }
}
