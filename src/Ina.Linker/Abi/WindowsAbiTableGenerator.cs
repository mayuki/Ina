using System.Text;

namespace Ina.Linker.Abi;

/// <summary>
/// Generates the import table for Windows (see <see cref="ImportLibrarySet.Parse"/>) from the export tables of
/// system DLLs. The table only records which DLL exports which name; no code is copied.
/// </summary>
public static class WindowsAbiTableGenerator
{
    /// <param name="libraries">
    /// The DLL images in the order in which a name that several of them export is attributed. A non-null filter
    /// restricts a DLL to the names it accepts.
    /// </param>
    public static void Generate(
        TextWriter output, string description, IReadOnlyList<(ReadOnlyMemory<byte> Image, Func<string, bool>? Filter)> libraries)
    {
        var tables = new List<(string Name, List<string> Exports)>();
        var seen = new HashSet<string>(StringComparer.Ordinal);
        foreach (var (image, filter) in libraries)
        {
            var (name, exports) = ReadExports(image.Span);
            tables.Add((name, exports.Where(export => (filter is null || filter(export)) && seen.Add(export)).Order(StringComparer.Ordinal).ToList()));
        }

        output.Write("# Generated by eng/GenerateWindowsAbi.cs. Do not edit by hand.\n");
        output.Write("# Names exported by the system DLLs; used to link without import libraries.\n");
        output.Write($"target {description}\n");
        output.Write($"needed {string.Join(' ', tables.Select(static t => t.Name))}\n");
        foreach (var (name, exports) in tables)
        {
            output.Write($"lib {name}\n");

            // Wrap the lines so that diffs of regenerated tables stay readable.
            var line = "F";
            foreach (var export in exports)
            {
                if (line.Length + export.Length + 1 > 120 && line.Length > 1)
                {
                    output.Write(line + "\n");
                    line = "F";
                }

                line += " " + export;
            }

            if (line.Length > 1)
            {
                output.Write(line + "\n");
            }
        }
    }

    /// <summary>Reads the name a DLL calls itself and the names it exports from its export directory.</summary>
    public static (string Name, IReadOnlyList<string> Exports) ReadExports(ReadOnlySpan<byte> image)
    {
        if (image.Length < 0x40 || image[0] != (byte)'M' || image[1] != (byte)'Z')
        {
            throw new LinkerException("not a PE image");
        }

        var header = (int)LittleEndian.U32(image, 0x3c);
        if (header + 24 > image.Length || LittleEndian.U32(image, header) != 0x4550)
        {
            throw new LinkerException("not a PE image");
        }

        int sectionCount = LittleEndian.U16(image, header + 6);
        int optionalHeaderSize = LittleEndian.U16(image, header + 20);
        var optionalHeader = header + 24;

        // The data directories follow the fixed part of the optional header, whose size depends on the format.
        var directories = optionalHeader + (LittleEndian.U16(image, optionalHeader) == 0x20b ? 112 : 96);
        var exportRva = LittleEndian.U32(image, directories);
        var sections = optionalHeader + optionalHeaderSize;

        if (exportRva == 0)
        {
            throw new LinkerException("the image has no export directory");
        }

        var sectionTable = image.Slice(sections, sectionCount * 40);
        var directory = Offset(sectionTable, exportRva);
        var name = LittleEndian.CString(image, Offset(sectionTable, LittleEndian.U32(image, directory + 12)));
        var nameCount = (int)LittleEndian.U32(image, directory + 24);
        var names = Offset(sectionTable, LittleEndian.U32(image, directory + 32));
        var exports = new List<string>(nameCount);
        for (var i = 0; i < nameCount; i++)
        {
            exports.Add(Encoding.ASCII.GetString(CStringBytes(image, Offset(sectionTable, LittleEndian.U32(image, names + i * 4)))));
        }

        return (name, exports);
    }

    /// <summary>Translates an address relative to the image base into an offset in the file.</summary>
    private static int Offset(ReadOnlySpan<byte> sectionTable, uint rva)
    {
        for (var section = 0; section < sectionTable.Length; section += 40)
        {
            var virtualAddress = LittleEndian.U32(sectionTable, section + 12);
            var size = Math.Max(LittleEndian.U32(sectionTable, section + 8), LittleEndian.U32(sectionTable, section + 16));
            if (rva >= virtualAddress && rva < virtualAddress + size)
            {
                return (int)(rva - virtualAddress + LittleEndian.U32(sectionTable, section + 20));
            }
        }

        throw new LinkerException($"address 0x{rva:x} is not inside any section");
    }

    private static ReadOnlySpan<byte> CStringBytes(ReadOnlySpan<byte> data, int offset)
    {
        var rest = data[offset..];
        var length = rest.IndexOf((byte)0);
        return length < 0 ? rest : rest[..length];
    }
}
